public class CharacterDatatype_08 {
    public static void main(String[] args) {
        char letter = 'A';  // Storing a single character
        char digit = '5';   // Storing a number as a character
        char symbol = '#';  // Storing a special symbol

        System.out.println(letter);  // Output: A
        System.out.println(digit);   // Output: 5
        System.out.println(symbol);  // Output: #
    }
}


